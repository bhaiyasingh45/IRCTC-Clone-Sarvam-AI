// E-mail content for ticket confirmation and cancellation.
// Gmail-safe HTML: nested tables + inline CSS only (no <style>, no external images/fonts), plus a plain-text twin.
// Every value that came from the browser goes through esc() — passenger names are user input.

const NAVY = '#1a3a6b';
const ORANGE = '#f97316';
const FONT = "Arial,Helvetica,sans-serif";

const esc = (v) => String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const inr = (n) => `₹${Number(n || 0).toLocaleString('en-IN')}`;
const GENDER = { M: 'Male', F: 'Female', T: 'Other' };
const BERTH = { LB: 'Lower', MB: 'Middle', UB: 'Upper', SL: 'Side Lower', SU: 'Side Upper' };
const CLASS = { SL: 'Sleeper (SL)', '3A': 'AC 3 Tier (3A)', '2A': 'AC 2 Tier (2A)', '1A': 'First AC (1A)' };

function fmtDate(iso) {
  const d = new Date(`${iso}T00:00:00Z`);
  return Number.isNaN(d.getTime()) ? String(iso) : d.toLocaleDateString('en-IN', { timeZone: 'UTC', weekday: 'short', day: '2-digit', month: 'short', year: 'numeric' });
}
const fmtDateTime = (iso) => {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? '' : d.toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hour12: true }) + ' IST';
};
const maskMobile = (m) => (/^\d{10}$/.test(m || '') ? `XXXXXX${m.slice(-4)}` : '');

// ── shared pieces ──────────────────────────────────────────────────────────
function shell({ preheader, bannerColor, bannerTitle, bannerSub, body }) {
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc(bannerTitle)}</title></head>
<body style="margin:0;padding:0;background:#eef1f6;">
<div style="display:none;max-height:0;overflow:hidden;opacity:0;color:transparent;">${esc(preheader)}</div>
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background:#eef1f6;"><tr><td align="center" style="padding:24px 12px;">
<table role="presentation" width="620" cellpadding="0" cellspacing="0" style="width:100%;max-width:620px;background:#ffffff;border-radius:8px;overflow:hidden;font-family:${FONT};color:#1f2937;">
  <tr><td style="height:4px;background:#FF9933;font-size:0;line-height:0;">&nbsp;</td></tr>
  <tr><td style="background:${NAVY};padding:18px 24px;">
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0"><tr>
      <td style="font-family:${FONT};"><span style="font-size:24px;font-weight:bold;color:${ORANGE};letter-spacing:1px;">IRCTC</span>
        <span style="font-size:12px;color:#c7d2e6;padding-left:8px;">Indian Railways · Demo</span></td>
      <td align="right" style="font-family:${FONT};font-size:11px;color:#c7d2e6;">e-Ticket service</td>
    </tr></table>
  </td></tr>
  <tr><td style="background:${bannerColor};padding:16px 24px;font-family:${FONT};">
    <div style="font-size:20px;font-weight:bold;color:#ffffff;">${esc(bannerTitle)}</div>
    <div style="font-size:13px;color:#ffffff;opacity:0.9;padding-top:4px;">${esc(bannerSub)}</div>
  </td></tr>
  <tr><td style="padding:22px 24px 8px 24px;">${body}</td></tr>
  <tr><td style="padding:8px 24px 22px 24px;">
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background:#fff7ed;border:1px solid #fed7aa;border-radius:6px;"><tr><td style="padding:12px 14px;font-family:${FONT};font-size:12px;line-height:1.5;color:#7c2d12;">
      <b>This is a demo e-mail.</b> It was generated by the RailSaarthi voice-booking demo, an IRCTC clone built for demonstration.
      It is <b>not a valid railway ticket</b> and no real booking, payment or refund has taken place.
    </td></tr></table>
  </td></tr>
  <tr><td style="background:#f3f4f6;padding:14px 24px;font-family:${FONT};font-size:11px;color:#6b7280;text-align:center;">
    Please do not reply to this automated message.
  </td></tr>
</table>
</td></tr></table>
</body></html>`;
}

const sectionTitle = (t) => `<div style="font-family:${FONT};font-size:12px;font-weight:bold;letter-spacing:1px;text-transform:uppercase;color:${NAVY};border-bottom:2px solid ${ORANGE};padding-bottom:6px;margin:22px 0 10px 0;">${esc(t)}</div>`;
const th = (t, align = 'left') => `<th align="${align}" style="padding:8px 10px;background:#f3f4f6;font-family:${FONT};font-size:12px;color:#374151;border-bottom:1px solid #e5e7eb;text-align:${align};">${esc(t)}</th>`;
const td = (t, { align = 'left', bold = false, color = '#1f2937', extra = '' } = {}) => `<td align="${align}" style="padding:8px 10px;font-family:${FONT};font-size:13px;color:${color};border-bottom:1px solid #f1f5f9;${bold ? 'font-weight:bold;' : ''}${extra}">${t}</td>`;

function pnrBox(pnr, { struck = false } = {}) {
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="border:1px dashed #9ca3af;border-radius:6px;background:#f9fafb;"><tr>
    <td style="padding:12px 16px;font-family:${FONT};font-size:12px;color:#6b7280;text-transform:uppercase;letter-spacing:1px;">PNR Number</td>
    <td align="right" style="padding:12px 16px;font-family:'Courier New',monospace;font-size:24px;font-weight:bold;letter-spacing:4px;color:${NAVY};${struck ? 'text-decoration:line-through;' : ''}">${esc(pnr)}</td>
  </tr></table>`;
}

function journeyBlock(b) {
  const t = b.train;
  const cell = (label, value) => `<td style="padding:6px 8px 6px 0;font-family:${FONT};vertical-align:top;"><div style="font-size:11px;color:#6b7280;text-transform:uppercase;">${esc(label)}</div><div style="font-size:14px;font-weight:bold;color:#111827;">${esc(value)}</div></td>`;
  return `<div style="font-family:${FONT};font-size:16px;font-weight:bold;color:${NAVY};padding:14px 0 8px 0;">${esc(t.number)} · ${esc(t.name)}</div>
  <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background:#f8fafc;border:1px solid #e5e7eb;border-radius:6px;"><tr>
    <td style="padding:14px 16px;font-family:${FONT};width:38%;"><div style="font-size:11px;color:#6b7280;">DEPARTS</div><div style="font-size:22px;font-weight:bold;color:#111827;">${esc(t.departure)}</div><div style="font-size:13px;color:#374151;">${esc(t.source)}</div></td>
    <td align="center" style="padding:14px 4px;font-family:${FONT};font-size:12px;color:#6b7280;">${esc(t.duration)}<br><span style="font-size:18px;color:${ORANGE};">&rarr;</span></td>
    <td align="right" style="padding:14px 16px;font-family:${FONT};width:38%;"><div style="font-size:11px;color:#6b7280;">ARRIVES</div><div style="font-size:22px;font-weight:bold;color:#111827;">${esc(t.arrival)}</div><div style="font-size:13px;color:#374151;">${esc(t.destination)}</div></td>
  </tr></table>
  <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin-top:10px;"><tr>
    ${cell('Journey date', fmtDate(b.travelDate))}${cell('Class', CLASS[b.class] || b.class)}${cell('Quota', b.quota || 'General')}
  </tr></table>`;
}

function passengerTable(passengers, withStatus) {
  const rows = passengers.map((p, i) => `<tr>${td(i + 1)}${td(esc(p.name), { bold: true })}${td(esc(p.age), { align: 'center' })}${td(esc(GENDER[p.gender] || p.gender))}${td(esc(BERTH[p.berth] || p.berth))}${withStatus ? td('CONFIRMED', { align: 'right', bold: true, color: '#15803d' }) : ''}</tr>`).join('');
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="border:1px solid #e5e7eb;border-radius:6px;border-collapse:separate;">
    <tr>${th('#')}${th('Passenger')}${th('Age', 'center')}${th('Gender')}${th('Berth preference')}${withStatus ? th('Status', 'right') : ''}</tr>${rows}</table>`;
}

const moneyRow = (label, value, { bold = false, color = '#1f2937', note = '', top = false } = {}) =>
  `<tr><td style="padding:8px 10px;font-family:${FONT};font-size:13px;color:${color};${bold ? 'font-weight:bold;' : ''}${top ? 'border-top:2px solid #d1d5db;' : 'border-bottom:1px solid #f1f5f9;'}">${esc(label)}${note ? `<div style="font-size:11px;font-weight:normal;color:#6b7280;padding-top:2px;">${esc(note)}</div>` : ''}</td>
  <td align="right" style="padding:8px 10px;font-family:${FONT};font-size:13px;color:${color};white-space:nowrap;vertical-align:top;${bold ? 'font-weight:bold;font-size:15px;' : ''}${top ? 'border-top:2px solid #d1d5db;' : 'border-bottom:1px solid #f1f5f9;'}">${esc(value)}</td></tr>`;
const moneyTable = (rows) => `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="border:1px solid #e5e7eb;border-radius:6px;border-collapse:separate;">${rows}</table>`;

const bullets = (items) => `<ul style="margin:0;padding-left:18px;font-family:${FONT};font-size:12px;line-height:1.7;color:#4b5563;">${items.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>`;

// ── booking confirmation ───────────────────────────────────────────────────
export function bookingEmail(b) {
  const f = b.fare;
  const route = `${b.train.source} → ${b.train.destination}`;
  const subject = `IRCTC e-Ticket (Demo) • PNR ${b.pnr} • ${route}, ${fmtDate(b.travelDate)}`;
  const mobile = maskMobile(b.contact);
  const body = `
    ${pnrBox(b.pnr)}
    ${journeyBlock(b)}
    ${sectionTitle('Passenger details')}
    ${passengerTable(b.passengers, true)}
    ${sectionTitle('Fare details')}
    ${moneyTable(
      moneyRow(`Ticket fare (${b.passengers.length} × ${CLASS[b.class] || b.class})`, inr(f.base)) +
      moneyRow('Reservation charge', inr(f.reservation)) +
      moneyRow('GST', inr(f.gst)) +
      moneyRow('Total fare paid', inr(f.total), { bold: true, color: NAVY, top: true }),
    )}
    ${sectionTitle('Booking information')}
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0">
      <tr>${td('Booked on', { color: '#6b7280' })}${td(esc(fmtDateTime(b.bookedAt)), { align: 'right' })}</tr>
      ${mobile ? `<tr>${td('Mobile number', { color: '#6b7280' })}${td(esc(mobile), { align: 'right' })}</tr>` : ''}
      <tr>${td('Payment', { color: '#6b7280' })}${td('Paid via UPI (demo)', { align: 'right' })}</tr>
    </table>
    ${sectionTitle('Important')}
    ${bullets([
      'Carry a valid photo ID of a passenger during the journey.',
      'Berth shown is the preference given at booking; seat allotment is not part of this demo.',
      'To cancel, ask the assistant or open "My Bookings". A cancellation charge and the non-refundable reservation fee apply.',
    ])}`;
  const html = shell({
    preheader: `Your ticket ${b.pnr} for ${route} on ${fmtDate(b.travelDate)} is confirmed. Total ${inr(f.total)}.`,
    bannerColor: '#15803d', bannerTitle: 'Booking Confirmed', bannerSub: `Your e-ticket for ${route} · ${fmtDate(b.travelDate)}`, body,
  });
  const text = [
    'IRCTC e-Ticket (DEMO) - Booking Confirmed', '',
    `PNR: ${b.pnr}`, `Train: ${b.train.number} ${b.train.name}`,
    `From: ${b.train.source}  ${b.train.departure}`, `To:   ${b.train.destination}  ${b.train.arrival}  (${b.train.duration})`,
    `Date: ${fmtDate(b.travelDate)}   Class: ${CLASS[b.class] || b.class}   Quota: ${b.quota || 'General'}`, '',
    'Passengers:', ...b.passengers.map((p, i) => `  ${i + 1}. ${p.name}, ${p.age}, ${GENDER[p.gender] || p.gender}, berth pref ${BERTH[p.berth] || p.berth} - CONFIRMED`), '',
    `Ticket fare: ${inr(f.base)}`, `Reservation charge: ${inr(f.reservation)}`, `GST: ${inr(f.gst)}`, `TOTAL PAID: ${inr(f.total)}`, '',
    `Booked on: ${fmtDateTime(b.bookedAt)}`, '',
    'This is a demo e-mail from the RailSaarthi demo (an IRCTC clone). It is not a valid railway ticket.',
  ].join('\n');
  return { subject, html, text };
}

// ── cancellation ───────────────────────────────────────────────────────────
export function cancellationEmail(b) {
  const r = b.refund;
  const route = `${b.train.source} → ${b.train.destination}`;
  const subject = `Ticket Cancelled (Demo) • PNR ${b.pnr} • Refund ${inr(r.refund)}`;
  const body = `
    ${pnrBox(b.pnr, { struck: true })}
    ${journeyBlock(b)}
    ${sectionTitle('Cancelled passengers')}
    ${passengerTable(b.passengers, false)}
    ${sectionTitle('Refund details')}
    ${moneyTable(
      moneyRow('Total fare paid', inr(r.paid)) +
      (r.reservationFee > 0 ? moneyRow('Less: reservation fee', `- ${inr(r.reservationFee)}`, { color: '#b91c1c', note: 'Never refunded on a cancelled ticket.' }) : '') +
      moneyRow('Less: cancellation charge', `- ${inr(r.charge)}`, { color: '#b91c1c', note: r.chargeReason }) +
      moneyRow('Refund amount', inr(r.refund), { bold: true, color: '#15803d', top: true }),
    )}
    <div style="font-family:${FONT};font-size:12px;color:#4b5563;padding-top:10px;line-height:1.6;">
      The refund of <b>${esc(inr(r.refund))}</b> will be credited to the original payment method in 5–7 working days (demo estimate).
    </div>
    ${sectionTitle('Cancellation information')}
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0">
      <tr>${td('Cancelled on', { color: '#6b7280' })}${td(esc(fmtDateTime(b.cancelledAt)), { align: 'right' })}</tr>
      <tr>${td('Originally booked on', { color: '#6b7280' })}${td(esc(fmtDateTime(b.bookedAt)), { align: 'right' })}</tr>
    </table>`;
  const html = shell({
    preheader: `Ticket ${b.pnr} (${route}) is cancelled. Refund ${inr(r.refund)}.`,
    bannerColor: '#b91c1c', bannerTitle: 'Ticket Cancelled', bannerSub: `${route} · ${fmtDate(b.travelDate)} · PNR ${b.pnr}`, body,
  });
  const text = [
    'IRCTC (DEMO) - Ticket Cancelled', '',
    `PNR: ${b.pnr}`, `Train: ${b.train.number} ${b.train.name}`, `${b.train.source} -> ${b.train.destination}, ${fmtDate(b.travelDate)}, ${CLASS[b.class] || b.class}`, '',
    'Passengers: ' + b.passengers.map((p) => p.name).join(', '), '',
    `Fare paid:               ${inr(r.paid)}`,
    ...(r.reservationFee > 0 ? [`Reservation fee (kept):  - ${inr(r.reservationFee)}`] : []),
    `Cancellation charge:     - ${inr(r.charge)}  (${r.chargeReason})`,
    `REFUND:                  ${inr(r.refund)}`, '',
    'Credited to the original payment method in 5-7 working days (demo estimate).', `Cancelled on: ${fmtDateTime(b.cancelledAt)}`, '',
    'This is a demo e-mail from the RailSaarthi demo (an IRCTC clone). No real refund takes place.',
  ].join('\n');
  return { subject, html, text };
}
